	if !strings.Contains(content, ".build/debug/bin/myapp") {
		t.Error("Missing debug variant output")
	}
	if !strings.Contains(content, ".build/release/bin/myapp") {
		t.Error("Missing release variant output")
	}

	// Verify default is first variant (debug)
	if !strings.Contains(content, "default debug") {
		t.Error("Default should be first variant (debug)")
	}
