// createMinimalConfig creates a minimal config for testing
func createMinimalConfig(targetName, targetType string, sources []string) *config.Config {
	return &config.Config{
		Name:     "test-project",
		BuildDir: ".build",
		Toolchain: config.Toolchain{
			Compiler: "clang",
			Std:      "c++20",
		},
		Targets: map[string]config.Target{
			targetName: {
				Name:    targetName,
				Type:    targetType,
				Sources: sources,
			},
		},
		Variants: map[string]config.Variant{
			"debug": {
				Name:      "debug",
				DebugInfo: true,
			},
		},
	}
}

func TestNinja_BasicStructure(t *testing.T) {
	cfg := createMinimalConfig("myapp", "executable", []string{"main.cpp"})

	var buf bytes.Buffer
	err := WriteNinjaTo(&buf, NinjaOptions{
		Config:    cfg,
		Variants:  []string{"debug"},
		BuildDir:  ".build",
		Toolchain: "clang",
		Platform:  toolchain.Platform{OS: "linux", Arch: "amd64"},
	})
	if err != nil {
		t.Fatalf("WriteNinjaTo failed: %v", err)
	}

	content := buf.String()

	// Verify header comment
	if !strings.Contains(content, "# Generated by clue") {
		t.Error("Missing generated comment")
	}

	// Verify cc rule
	if !strings.Contains(content, "rule cc") {
		t.Error("Missing cc rule")
	}

	// Verify cxx rule
	if !strings.Contains(content, "rule cxx") {
		t.Error("Missing cxx rule")
	}

	// Verify link rule
	if !strings.Contains(content, "rule link") {
		t.Error("Missing link rule")
	}

	// Verify build statement for source
	if !strings.Contains(content, "build .build/debug/myapp/obj/main.cpp.o") {
		t.Errorf("Missing build statement for main.cpp.o, got:\n%s", content)
	}

	// Verify link statement
	if !strings.Contains(content, "build .build/debug/bin/myapp") {
		t.Errorf("Missing link statement for myapp, got:\n%s", content)
	}

	// Verify phony target
	if !strings.Contains(content, "build debug: phony") {
		t.Errorf("Missing phony target for debug, got:\n%s", content)
	}

	// Verify default target
	if !strings.Contains(content, "default debug") {
		t.Errorf("Missing default target, got:\n%s", content)
	}
}

