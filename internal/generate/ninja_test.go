func TestNinja_WriteIfChanged(t *testing.T) {
	tmpDir := t.TempDir()
	outputPath := filepath.Join(tmpDir, "build.ninja")

	cfg := createMinimalConfig("myapp", "executable", []string{"main.cpp"})
	opts := NinjaOptions{
		Config:     cfg,
		Variants:   []string{"debug"},
		BuildDir:   ".build",
		OutputPath: outputPath,
		Toolchain:  "clang",
		Platform:   toolchain.Platform{OS: "linux", Arch: "amd64"},
	}

	// Generate first time
	err := Ninja(opts)
	if err != nil {
		t.Fatalf("First Ninja failed: %v", err)
	}

	// Get file info
	info1, err := os.Stat(outputPath)
	if err != nil {
		t.Fatalf("Failed to stat file: %v", err)
	}
	mtime1 := info1.ModTime()

	// Generate second time with same content - should not modify
	err = Ninja(opts)
	if err != nil {
		t.Fatalf("Second Ninja failed: %v", err)
	}

	info2, err := os.Stat(outputPath)
	if err != nil {
		t.Fatalf("Failed to stat file after second write: %v", err)
	}
	mtime2 := info2.ModTime()

	// Mtime should be the same (file wasn't rewritten)
	if !mtime1.Equal(mtime2) {
		t.Error("File was rewritten even though content was unchanged")
	}
}

func TestNinja_CCompiler(t *testing.T) {
	// Test that C files use cc rule, not cxx
	cfg := createMinimalConfig("myapp", "executable", []string{"main.c"})

	var buf bytes.Buffer
	err := WriteNinjaTo(&buf, NinjaOptions{
		Config:    cfg,
		Variants:  []string{"debug"},
		BuildDir:  ".build",
		Toolchain: "clang",
		Platform:  toolchain.Platform{OS: "linux", Arch: "amd64"},
	})
	if err != nil {
		t.Fatalf("WriteNinjaTo failed: %v", err)
	}

	content := buf.String()

	// Verify C file uses cc rule (has cflags, not cxxflags)
	if !strings.Contains(content, "build .build/debug/myapp/obj/main.c.o: cc main.c") {
		t.Errorf("C file should use cc rule, got:\n%s", content)
	}

	// Verify cflags is set for the C build
	if !strings.Contains(content, "cflags =") {
		t.Error("Missing cflags for C compilation")
	}
}

