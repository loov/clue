func TestNinja_WriteFile(t *testing.T) {
	// Create temp directory
	tmpDir := t.TempDir()

	cfg := createMinimalConfig("myapp", "executable", []string{"main.cpp"})

	outputPath := filepath.Join(tmpDir, "build.ninja")
	err := Ninja(NinjaOptions{
		Config:     cfg,
		Variants:   []string{"debug"},
		BuildDir:   ".build",
		OutputPath: outputPath,
		Toolchain:  "clang",
		Platform:   build.Platform{OS: "linux", Arch: "amd64"},
	})
	if err != nil {
		t.Fatalf("Ninja failed: %v", err)
	}

	// Verify file exists
	if _, err := os.Stat(outputPath); os.IsNotExist(err) {
		t.Fatal("build.ninja was not created")
	}

	// Read and verify content
	content, err := os.ReadFile(outputPath)
	if err != nil {
		t.Fatalf("Failed to read build.ninja: %v", err)
	}

	if !strings.Contains(string(content), "rule cc") {
		t.Error("Generated file missing cc rule")
	}
}

func TestNinja_WriteIfChanged(t *testing.T) {
	tmpDir := t.TempDir()
	outputPath := filepath.Join(tmpDir, "build.ninja")

	cfg := createMinimalConfig("myapp", "executable", []string{"main.cpp"})
	opts := NinjaOptions{
		Config:     cfg,
		Variants:   []string{"debug"},
		BuildDir:   ".build",
		OutputPath: outputPath,
		Toolchain:  "clang",
		Platform:   build.Platform{OS: "linux", Arch: "amd64"},
	}

	// Generate first time
	err := Ninja(opts)
	if err != nil {
		t.Fatalf("First Ninja failed: %v", err)
	}

	// Get file info
	info1, err := os.Stat(outputPath)
	if err != nil {
		t.Fatalf("Failed to stat file: %v", err)
	}
	mtime1 := info1.ModTime()

	// Generate second time with same content - should not modify
	err = Ninja(opts)
	if err != nil {
		t.Fatalf("Second Ninja failed: %v", err)
	}

	info2, err := os.Stat(outputPath)
	if err != nil {
		t.Fatalf("Failed to stat file after second write: %v", err)
	}
	mtime2 := info2.ModTime()

	// Mtime should be the same (file wasn't rewritten)
	if !mtime1.Equal(mtime2) {
		t.Error("File was rewritten even though content was unchanged")
	}
}

